//! `cargo xtask oui`: regenerate `crates/sensr-fingerprint/data/oui.tsv` from
//! the IEEE MA-L, MA-M and MA-S registries. `--check` exits non-zero if the
//! committed table differs from what the registries give today.

use std::collections::BTreeMap;
use std::fs;
use std::io::Read;
use std::path::Path;
use std::time::Duration;

use anyhow::{Context, Result, bail};

const SOURCES: [&str; 3] = [
    "https://standards-oui.ieee.org/oui/oui.csv",
    "https://standards-oui.ieee.org/oui28/mam.csv",
    "https://standards-oui.ieee.org/oui36/oui36.csv",
];
const USER_AGENT: &str = "sensr-xtask (+https://github.com/itpick/sensr)";
const TABLE_PATH: &str = "crates/sensr-fingerprint/data/oui.tsv";
const HEADER: &str = "# generated by cargo xtask oui from IEEE registries; do not edit";
const ATTEMPTS: u32 = 3;
const MAX_BYTES: u64 = 64 * 1024 * 1024;

#[derive(clap::Args)]
pub struct Args {
    /// Exit 1 if regenerating would change the committed table.
    #[arg(long)]
    check: bool,
}

pub fn run(root: &Path, args: &Args) -> Result<()> {
    let mut bodies = Vec::new();
    for url in SOURCES {
        bodies.push(download(url)?);
    }
    let table = build_table(&bodies)?;
    let path = root.join(TABLE_PATH);
    if args.check {
        let current = fs::read_to_string(&path).unwrap_or_default();
        if current != table {
            bail!("{TABLE_PATH} is out of date; run `cargo xtask oui`");
        }
        println!(
            "{TABLE_PATH} is up to date ({} lines)",
            table.lines().count()
        );
        return Ok(());
    }
    fs::write(&path, &table).with_context(|| format!("writing {}", path.display()))?;
    println!(
        "wrote {TABLE_PATH} ({} lines, {} bytes)",
        table.lines().count(),
        table.len()
    );
    Ok(())
}

fn download(url: &str) -> Result<String> {
    let agent: ureq::Agent = ureq::Agent::config_builder()
        .http_status_as_error(false)
        .timeout_global(Some(Duration::from_secs(120)))
        .user_agent(USER_AGENT)
        .build()
        .into();
    let mut last = String::new();
    for attempt in 1..=ATTEMPTS {
        match agent.get(url).call() {
            Ok(mut resp) if resp.status().as_u16() == 200 => {
                let mut body = String::new();
                resp.body_mut()
                    .as_reader()
                    .take(MAX_BYTES)
                    .read_to_string(&mut body)
                    .with_context(|| format!("reading {url}"))?;
                return Ok(body);
            }
            Ok(resp) => last = format!("HTTP {}", resp.status()),
            Err(e) => last = e.to_string(),
        }
        eprintln!("{url}: attempt {attempt}/{ATTEMPTS} failed: {last}");
        if attempt < ATTEMPTS {
            std::thread::sleep(Duration::from_secs(2 * u64::from(attempt)));
        }
    }
    bail!("{url}: {last}")
}

/// The TSV for the given registry CSV bodies: `PREFIX<TAB>short name`, sorted
/// by prefix, the first body winning on a repeated prefix.
fn build_table(bodies: &[String]) -> Result<String> {
    let mut rows: BTreeMap<String, String> = BTreeMap::new();
    for body in bodies {
        for (n, rec) in parse_csv(body).into_iter().enumerate() {
            if n == 0 && rec.first().is_some_and(|c| c == "Registry") {
                continue;
            }
            if rec.len() < 3 {
                bail!("short CSV record: {rec:?}");
            }
            let prefix = rec[1].trim().to_ascii_uppercase();
            if !matches!(prefix.len(), 6 | 7 | 9) || !prefix.bytes().all(|b| b.is_ascii_hexdigit())
            {
                bail!("bad assignment {:?} in {rec:?}", rec[1]);
            }
            if placeholder(&rec[2]) {
                continue;
            }
            let name = short_name(&rec[2]).replace(['\t', '\n', '\r'], " ");
            if name.is_empty() {
                continue;
            }
            rows.entry(prefix).or_insert(name);
        }
    }
    let mut out = String::from(HEADER);
    out.push('\n');
    for (p, n) in rows {
        out.push_str(&p);
        out.push('\t');
        out.push_str(&n);
        out.push('\n');
    }
    Ok(out)
}

/// RFC 4180 CSV: quoted fields may hold commas, newlines and `""`.
fn parse_csv(text: &str) -> Vec<Vec<String>> {
    let text = text.strip_prefix('\u{feff}').unwrap_or(text);
    let mut records = Vec::new();
    let mut rec: Vec<String> = Vec::new();
    let mut field = String::new();
    let mut quoted = false;
    let mut chars = text.chars().peekable();
    while let Some(c) = chars.next() {
        if quoted {
            match c {
                '"' if chars.peek() == Some(&'"') => {
                    chars.next();
                    field.push('"');
                }
                '"' => quoted = false,
                _ => field.push(c),
            }
            continue;
        }
        match c {
            '"' => quoted = true,
            ',' => rec.push(std::mem::take(&mut field)),
            '\r' => {}
            '\n' => {
                rec.push(std::mem::take(&mut field));
                records.push(std::mem::take(&mut rec));
            }
            _ => field.push(c),
        }
    }
    if !field.is_empty() || !rec.is_empty() {
        rec.push(field);
        records.push(rec);
    }
    records.retain(|r| !(r.len() == 1 && r[0].is_empty()));
    records
}

/// Legal-form and filler words removed from the end of a name, longest first.
