/// `(prefix, short name)`; matched case-insensitively against the original.
const ALIASES: [(&str, &str); 25] = [
    ("Raspberry Pi", "Raspberry Pi"),
    ("Hon Hai Precision", "Foxconn"),
    ("Apple", "Apple"),
    ("Google", "Google"),
    ("Amazon Technologies", "Amazon"),
    ("Samsung Electronics", "Samsung"),
    ("Espressif", "Espressif"),
    ("Sonos", "Sonos"),
    ("Wyze Labs", "Wyze"),
    ("Ubiquiti", "Ubiquiti"),
    ("TP-LINK", "TP-Link"),
    ("TP-Link", "TP-Link"),
    ("Hewlett Packard", "HP"),
    ("Intel Corporate", "Intel"),
    ("Microsoft", "Microsoft"),
    ("Nintendo", "Nintendo"),
    ("Sony Interactive", "PlayStation"),
    ("Roku", "Roku"),
    ("Ring LLC", "Ring"),
    ("Reolink", "Reolink"),
    ("Synology", "Synology"),
    ("Netgear", "Netgear"),
    ("ASUSTek", "ASUS"),
    ("Realtek", "Realtek"),
    ("Lite-On", "Lite-On"),
];
const ALIASES_MORE: [(&str, &str); 3] = [
    ("Liteon", "Lite-On"),
    ("Murata", "Murata"),
    ("AzureWave", "AzureWave"),
];

/// Organisation names that name nobody: IEEE's hidden ("Private")
/// registrations, and the 6-digit parents of MA-M / MA-S blocks, whose
/// children carry the real names. Left out, a lookup finds the child or
/// nothing.
fn placeholder(raw: &str) -> bool {
    let name = raw.split_whitespace().collect::<Vec<_>>().join(" ");
    name.eq_ignore_ascii_case("Private") || name.eq_ignore_ascii_case("IEEE Registration Authority")
}

/// Trimmed off the end of a name, before and after each suffix: what a
/// removed `& Co. KG` or `+ Co` leaves dangling.
fn is_sep(c: char) -> bool {
    matches!(c, ',' | '.' | ' ' | '&' | '-' | '+' | '/')
}

/// True when `name` starts with `prefix` (ASCII case-insensitive) and the
/// match ends on a word boundary, so `Apple` does not claim `Applied ...`.
fn has_word_prefix(name: &str, prefix: &str) -> bool {
    let (Some(head), rest) = (name.get(..prefix.len()), name.get(prefix.len()..)) else {
        return false;
    };
    head.eq_ignore_ascii_case(prefix)
        && rest
            .and_then(|r| r.chars().next())
            .is_none_or(|c| !c.is_alphanumeric())
}

/// The short display name for an IEEE organisation name.
fn short_name(raw: &str) -> String {
    let name = raw.split_whitespace().collect::<Vec<_>>().join(" ");
    if name.is_empty() {
        return name;
    }
    for (prefix, short) in ALIASES.iter().chain(ALIASES_MORE.iter()) {
        if has_word_prefix(&name, prefix) {
            return (*short).to_owned();
        }
    }
    let mut cur = name.clone();
    'strip: loop {
        let trimmed = cur.trim_end_matches(is_sep);
        let lower = trimmed.to_ascii_lowercase();
        for suf in SUFFIXES {
            let Some(head) = lower.strip_suffix(suf) else {
                continue;
            };
            // a whole word: start of name or a separator right before it
            if head.chars().next_back().is_some_and(char::is_alphanumeric) {
                continue;
            }
            let rest = trimmed[..head.len()].trim_end_matches(is_sep);
            if rest.is_empty() {
                break 'strip;
            }
            cur = rest.to_owned();
            continue 'strip;
        }
        break;
    }
    let cur = cur.trim_end_matches(is_sep).to_owned();
    if let Some((first, rest)) = cur.split_once(' ')
        && first.eq_ignore_ascii_case("shenzhen")
        && let Some(word) = rest.split_whitespace().next()
    {
        return word.to_owned();
    }
    cur
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn short_name_strips_suffixes() {
        assert_eq!(short_name("Wyze Labs Inc"), "Wyze");
        assert_eq!(short_name("Shenzhen Bilian Electronic Co.,Ltd"), "Bilian");
        assert_eq!(short_name("Hon Hai Precision Ind. Co.,Ltd."), "Foxconn");
        assert_eq!(short_name("Raspberry Pi Trading Ltd"), "Raspberry Pi");
        assert_eq!(short_name("Brother Industries, Ltd."), "Brother Industries");
    }

    #[test]
    fn short_name_edge_cases() {
        assert_eq!(short_name("  Foo   Bar  GmbH "), "Foo Bar");
        assert_eq!(short_name("Technologies"), "Technologies");
        assert_eq!(short_name("Applied Materials Inc"), "Applied Materials");
        assert_eq!(short_name("Acme S.A."), "Acme");
        assert_eq!(short_name("Cisco Systems, Inc"), "Cisco Systems");
    }

    #[test]
    fn short_name_drops_dangling_joiners() {
        assert_eq!(short_name("Pilz GmbH & Co. KG"), "Pilz");
        assert_eq!(short_name("HOB ELECTRONIC GMBH & CO. KG"), "HOB ELECTRONIC");
        assert_eq!(
            short_name("ELZET80 Mikrocomputer GmbH&Co. KG"),
            "ELZET80 Mikrocomputer"
        );
        assert_eq!(short_name("Canal +"), "Canal");
        assert_eq!(short_name("CDS-"), "CDS");
        assert_eq!(short_name("Foo /"), "Foo");
        assert_eq!(
            short_name("Endress & Hauser GmbH & Co. KG"),
            "Endress & Hauser"
        );
        // inside a name they stay
        assert_eq!(short_name("TP-Link Systems Inc"), "TP-Link");
        assert_eq!(short_name("Black & Decker Inc"), "Black & Decker");
    }

    #[test]
    fn placeholder_organisations_are_left_out() {
        let csv = "Registry,Assignment,Organization Name,Organization Address\n\
                   MA-L,000101,Private,x\n\
                   MA-L,0055DA,IEEE Registration Authority,x\n\
                   MA-M,0055DA1,\"Foo, Inc.\",x\n\
                   MA-L,B827EB,\"Raspberry Pi Trading Ltd\",x\n";
        let t = build_table(&[csv.to_owned()]).unwrap();
        let lines: Vec<&str> = t.lines().skip(1).collect();
        assert_eq!(lines, ["0055DA1\tFoo", "B827EB\tRaspberry Pi"]);
        assert!(placeholder(" private "));
        assert!(!placeholder("Private Networks Ltd"));
    }

    #[test]
    fn csv_parses_quoted_commas() {
        let text = "Registry,Assignment,Organization Name,Organization Address\r\n\
                    MA-L,B827EB,\"Raspberry Pi Trading Ltd\",\"Maurice Wilkes Building, Cowley Road\"\r\n\
                    MA-L,001122,\"Say \"\"hi\"\", Co.\",\"line one\nline two\"\r\n";
        let recs = parse_csv(text);
        assert_eq!(recs.len(), 3);
        assert_eq!(recs[1][3], "Maurice Wilkes Building, Cowley Road");
        assert_eq!(recs[2][2], "Say \"hi\", Co.");
        assert_eq!(recs[2][3], "line one\nline two");
    }

    #[test]
    fn table_is_sorted_and_headed() {
        let csv = "Registry,Assignment,Organization Name,Organization Address\n\
                   MA-L,B827EB,\"Raspberry Pi Trading Ltd\",x\n\
                   MA-S,0055DA123,\"Foo, Inc.\",x\n\
                   MA-L,0055DA,\"Bar Corp\",x\n";
        let t = build_table(&[csv.to_owned()]).unwrap();
        let lines: Vec<&str> = t.lines().collect();
        assert_eq!(lines[0], HEADER);
        assert_eq!(
            &lines[1..],
            ["0055DA\tBar", "0055DA123\tFoo", "B827EB\tRaspberry Pi"]
        );
    }
}
