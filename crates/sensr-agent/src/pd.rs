//! IPv6 prefix delegation on the box: networkd runs the DHCPv6 client and
//! hands /64s to the tracking LANs; sensr keeps the delegation's state
//! machine (`sensr-net::ipv6::pd`) next to it: every 10 s it observes what
//! the kernel holds, persists it under `/var/lib/sensr/state/pd/`, and when
//! the prefix changes (ISP renumbering, or a new prefix after a reboot)
//! advertises the old /64s as deprecated (preferred lifetime 0, valid
//! lifetime counting down, RFC 9096) through a networkd drop-in, which
//! networkd itself forgets to do.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::sync::{Arc, Mutex};
use std::time::Duration;

use sensr_apply::cmd::{Cmd, Runner};
use sensr_net::ipv6::pd::{
    AdvertisedPrefix, Consumer, PdState, PdStore, observe::observation_from_kernel,
};
use sensr_schema::Document;
use sensr_schema::models::interfaces::Ipv6Config;
use serde::Serialize;

const POLL: Duration = Duration::from_secs(10);
/// networkd drop-in carrying the deprecated prefixes of one LAN.
const DROPIN: &str = "60-sensr-stale-prefixes.conf";

/// One uplink and the LANs tracking it.
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct Uplink {
    /// logical id (`wan`)
    pub interface: String,
    /// kernel device
    pub device: String,
    /// tracking LANs: logical id, device, prefix id
    pub consumers: Vec<(String, String, u64)>,
}

/// Uplinks with a DHCPv6 client and at least one tracking LAN.
pub fn uplinks(doc: &Document) -> Vec<Uplink> {
    let mut out = Vec::new();
    for (id, i) in doc.interfaces.iter().filter(|(_, i)| i.enabled) {
        if !matches!(i.ipv6, Ipv6Config::Dhcp6 { .. }) {
            continue;
        }
        let consumers: Vec<(String, String, u64)> = doc
            .interfaces
            .iter()
            .filter(|(_, l)| l.enabled)
            .filter_map(|(lid, l)| match &l.ipv6 {
                Ipv6Config::Track {
                    interface,
                    prefix_id,
                } if interface == id => {
                    Some((lid.to_string(), l.device.to_string(), u64::from(*prefix_id)))
                }
                _ => None,
            })
            .collect();
        if !consumers.is_empty() {
            out.push(Uplink {
                interface: id.to_string(),
                device: i.device.to_string(),
                consumers,
            });
        }
    }
    out
}

/// The drop-in text for deprecated prefixes (empty list: none).
pub fn dropin(prefixes: &[AdvertisedPrefix]) -> String {
    let mut s = String::from(
        "# Generated by sensr: prefixes of an earlier delegation, deprecated (RFC 9096).\n",
    );
    for p in prefixes.iter().filter(|p| p.deprecated) {
        s.push_str(&format!(
            "\n[IPv6Prefix]\nPrefix={}\nPreferredLifetimeSec=0\nValidLifetimeSec={}\n",
            p.prefix,
            p.valid_lifetime_secs.max(1)
        ));
    }
    s
}

/// Status for `sensr runtime ipv6` and the UI.
#[derive(Clone, Debug, Serialize)]
pub struct PdView {
    /// uplink logical id
    pub interface: String,
    /// persisted state (current and stale prefixes)
    pub state: PdState,
    /// what each LAN advertises now
    pub advertised: BTreeMap<String, Vec<AdvertisedPrefix>>,
}

struct Tracked {
    uplink: Uplink,
    state: PdState,
    store: PdStore,
    /// device → deprecated prefixes last written
    written: BTreeMap<String, Vec<String>>,
}

/// The PD watcher.
pub struct PdService {
    runner: Arc<dyn Runner>,
    root: PathBuf,
    dir: PathBuf,
    tracked: Mutex<Vec<Tracked>>,
}

fn now() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0)
}

fn lock<T>(m: &Mutex<T>) -> std::sync::MutexGuard<'_, T> {
    m.lock().unwrap_or_else(|e| e.into_inner())
}

impl PdService {
    /// Persists under `dir`; networkd files live under `root`.
    pub fn new(
        runner: Arc<dyn Runner>,
        root: impl Into<PathBuf>,
        dir: impl Into<PathBuf>,
    ) -> Arc<PdService> {
        Arc::new(PdService {
            runner,
            root: root.into(),
            dir: dir.into(),
            tracked: Mutex::new(Vec::new()),
        })
    }

    /// Starts polling in a thread.
    pub fn start(self: &Arc<Self>) {
        let s = Arc::clone(self);
        let r = std::thread::Builder::new()
            .name("sensr-pd".into())
            .spawn(move || {
                loop {
                    s.tick(now());
                    std::thread::sleep(POLL);
                }
            });
        if let Err(e) = r {
            tracing::error!(error = %e, "PD watcher not started");
        }
    }

    /// After an apply: track the document's uplinks (loading their state).
    pub fn applied(&self, doc: &Document) {
        let ups = uplinks(doc);
        let mut t = lock(&self.tracked);
        t.retain(|x| ups.iter().any(|u| u.interface == x.uplink.interface));
        for u in ups {
            if let Some(x) = t.iter_mut().find(|x| x.uplink.interface == u.interface) {
                x.uplink = u;
                continue;
            }
            let store = PdStore::new(self.dir.join(format!("{}.json", u.interface)));
            let loaded = store.load();
            if let Some(issue) = &loaded.issue {
                tracing::info!(uplink = %u.interface, ?issue, "PD state");
            }
            t.push(Tracked {
                uplink: u,
                state: loaded.state,
                store,
                written: BTreeMap::new(),
            });
        }
    }

    fn json(&self, args: &[&str]) -> Vec<u8> {
        match self
            .runner
            .run(&Cmd::new("ip").args(args.iter().copied()), None)
        {
            Ok(o) if o.success() => o.stdout,
            _ => b"[]".to_vec(),
        }
    }

    fn dropin_path(&self, device: &str) -> PathBuf {
        self.root
            .join("run/systemd/network")
            .join(format!("40-sensr-{device}.network.d"))
            .join(DROPIN)
    }

    /// One poll at `now`.
    pub fn tick(&self, now: u64) {
        let mut t = lock(&self.tracked);
        if t.is_empty() {
            return;
        }
        let routes = self.json(&["-j", "-6", "route", "show", "table", "all"]);
        let addrs = self.json(&["-j", "-6", "addr", "show"]);
        let mut reload = false;
        for x in t.iter_mut() {
            let lans: Vec<&str> = x
                .uplink
                .consumers
                .iter()
                .map(|(_, d, _)| d.as_str())
                .collect();
            let obs = match observation_from_kernel(&routes, &addrs, &lans) {
                Ok(k) => {
                    for m in &k.mismatches {
                        tracing::debug!(?m, "PD lifetime mismatch");
                    }
                    k.observation
                }
                Err(e) => {
                    tracing::warn!(uplink = %x.uplink.interface, error = %e, "PD observation");
                    continue;
                }
            };
            let mut events = x.state.observe(now, obs);
            events.extend(x.state.expire(now));
            for e in &events {
                tracing::info!(uplink = %x.uplink.interface, event = ?e, "prefix delegation");
            }
            if !events.is_empty()
                && let Err(e) = x.store.save(&x.state)
            {
                tracing::warn!(error = %e, "PD state not saved");
            }
            let consumers: Vec<Consumer> = x
                .uplink
                .consumers
                .iter()
                .map(|(id, _, pid)| Consumer::new(id.clone(), *pid))
                .collect();
            let adv = x.state.advertised(now, &consumers);
            for (id, dev, _) in &x.uplink.consumers {
                let list = adv.get(id).cloned().unwrap_or_default();
                let stale: Vec<String> = list
                    .iter()
                    .filter(|p| p.deprecated)
                    .map(|p| p.prefix.to_string())
                    .collect();
                if x.written.get(dev) == Some(&stale) {
                    continue;
                }
                let path = self.dropin_path(dev);
                let res = if stale.is_empty() {
                    match std::fs::remove_file(&path) {
                        Err(e) if e.kind() != std::io::ErrorKind::NotFound => Err(e),
                        _ => Ok(()),
                    }
                } else {
                    write(&path, dropin(&list).as_bytes())
                };
                match res {
                    Ok(()) => {
                        reload = true;
                        x.written.insert(dev.clone(), stale);
                    }
                    Err(e) => {
                        tracing::warn!(path = %path.display(), error = %e, "stale-prefix drop-in")
                    }
                }
            }
        }
        drop(t);
        if reload {
            match self
                .runner
                .run(&Cmd::new("networkctl").args(["reload"]), None)
            {
                Ok(o) if o.success() => tracing::info!("deprecated prefixes advertised"),
                Ok(o) => tracing::warn!(error = %o.stderr_text(), "networkctl reload"),
                Err(e) => tracing::warn!(error = %e, "networkctl reload"),
            }
        }
    }

    /// Status per uplink.
    pub fn view(&self, now: u64) -> Vec<PdView> {
        lock(&self.tracked)
            .iter()
            .map(|x| {
                let consumers: Vec<Consumer> = x
                    .uplink
                    .consumers
                    .iter()
                    .map(|(id, _, pid)| Consumer::new(id.clone(), *pid))
                    .collect();
                PdView {
                    interface: x.uplink.interface.clone(),
                    advertised: x.state.advertised(now, &consumers),
                    state: x.state.clone(),
                }
            })
            .collect()
    }
}

fn write(path: &Path, data: &[u8]) -> std::io::Result<()> {
    if let Some(d) = path.parent() {
        std::fs::create_dir_all(d)?;
        use std::os::unix::fs::PermissionsExt;
        let _ = std::fs::set_permissions(d, std::fs::Permissions::from_mode(0o755));
    }
    let tmp = path.with_extension("tmp");
    std::fs::write(&tmp, data)?;
    use std::os::unix::fs::PermissionsExt;
    std::fs::set_permissions(&tmp, std::fs::Permissions::from_mode(0o644))?;
    std::fs::rename(tmp, path)
}

#[cfg(test)]
mod tests {
    use super::*;
    use sensr_apply::cmd::{FakeRunner, Output};

    fn home_router() -> Document {
        serde_json::from_str(include_str!(
            "../../sensr-import-opnsense/tests/golden/home-router.sensr.json"
        ))
        .unwrap()
    }

    fn kernel(prefix: &str, lan64: &str) -> (String, String) {
        let routes = format!(
            r#"[{{"type":"unreachable","dst":"{prefix}","dev":"lo","protocol":"dhcp","metric":1024,"expires":3539}}]"#
        );
        let addrs = format!(
            r#"[{{"ifname":"igc1","addr_info":[{{"family":"inet6","local":"{lan64}1","prefixlen":64,"scope":"global","dynamic":true,"valid_life_time":3540,"preferred_life_time":1740}}]}}]"#
        );
        (routes, addrs)
    }

    fn runner(state: Arc<Mutex<(String, String)>>) -> Arc<FakeRunner> {
        let r = Arc::new(FakeRunner::new());
        r.respond(move |c, _| {
            let args: Vec<String> = c
                .get_args()
                .iter()
                .map(|a| a.to_string_lossy().into_owned())
                .collect();
            let s = state.lock().unwrap();
            let body = if args.iter().any(|a| a == "route") {
                s.0.clone()
            } else if args.iter().any(|a| a == "addr") {
                s.1.clone()
            } else {
                return None;
            };
            Some(Output {
                stdout: body.into_bytes(),
                ..Output::ok()
            })
        });
        r
    }

    #[test]
    fn uplinks_of_the_home_router() {
        let u = uplinks(&home_router());
        assert_eq!(u.len(), 1);
        assert_eq!(u[0].interface, "wan");
        assert!(
            u[0].consumers
                .iter()
                .any(|(id, _, pid)| id == "lan" && *pid == 0)
        );
    }

    #[test]
    fn renumbering_deprecates_the_old_prefix_and_survives_a_restart() {
        let root = tempfile::tempdir().unwrap();
        let state = Arc::new(Mutex::new(kernel(
            "2001:db8:1:100::/56",
            "2001:db8:1:100::",
        )));
        let r = runner(state.clone());
        let svc = PdService::new(r.clone(), root.path(), root.path().join("pd"));
        let doc = home_router();
        svc.applied(&doc);
        let t0 = 1_800_000_000;
        svc.tick(t0);
        let dropin = root
            .path()
            .join("run/systemd/network/40-sensr-igc1.network.d")
            .join(DROPIN);
        assert!(!dropin.exists());
        assert!(root.path().join("pd/wan.json").exists(), "state persisted");
        // the ISP hands out another /56
        *state.lock().unwrap() = kernel("2001:db8:2:200::/56", "2001:db8:2:200::");
        svc.tick(t0 + 60);
        let text = std::fs::read_to_string(&dropin).unwrap();
        assert!(text.contains("Prefix=2001:db8:1:100::/64"), "{text}");
        assert!(text.contains("PreferredLifetimeSec=0"));
        assert!(
            r.call_lines()
                .iter()
                .any(|l| l.contains("networkctl") && l.contains("reload"))
        );
        let view = svc.view(t0 + 60);
        assert!(view[0].advertised["lan"].iter().any(|p| p.deprecated));

        // reboot: a new process loads the state and still deprecates
        let r2 = runner(state);
        let svc2 = PdService::new(r2, root.path(), root.path().join("pd"));
        std::fs::remove_file(&dropin).unwrap();
        svc2.applied(&doc);
        svc2.tick(t0 + 120);
        assert!(
            std::fs::read_to_string(&dropin)
                .unwrap()
                .contains("2001:db8:1:100::/64")
        );
        // and once the old prefix expired, the drop-in goes away
        svc2.tick(t0 + 120 + 6_000);
        assert!(!dropin.exists());
    }
}
